"""Deployment bundle: the bot's code + ONLY the TikTok-related state of the profiles the bot uses.

Why not just copy the profile folders: the master profile is a copy of a person's everyday Brave profile and holds
their whole browsing life - history, saved passwords, autofill, bookmarks, extensions, and the cookies / local data
of every other site. None of that may leave the machine. A website can only ever see its own origin's storage, so
what a TikTok session needs is exactly:
  * the TikTok cookies,
  * TikTok's localStorage (device ids, the ticket-guard public key, ...),
  * TikTok's IndexedDB (the ticket-guard key store).
`package` exports those three things per profile (and nothing else - no history, no passwords, no other sites,
no Local State, no extensions, no cache) and `restore_profiles` rebuilds a clean profile folder from them on the
server. Cookies are written in clear text on purpose: a Windows profile's cookies are encrypted with a key tied to
that Windows user + machine (a Linux server cannot read them), so they travel as JSON and are re-encrypted by the
server's own browser; the importer deletes the clear-text file after use.
"""
import hashlib
import json
import os
import shutil
import sqlite3
import time
from pathlib import Path

import config
from app import accounts as acct
from app.bfp_loader import ensure_bfp_on_path

ensure_bfp_on_path()
import bfp  # noqa: E402

SECRET_NAMES = ("KEY", "TOKEN", "SECRET", "PASSWORD", "PASSWD")
CODE_FILES = ("run.py", "config.py", "README.md", ".env.example", "requirements.txt")
CODE_DIRS = ("app", "tests", "deploy")
# anything with one of these names must never appear inside a bundle (verify_bundle checks)
FORBIDDEN_NAMES = {"Login Data", "Login Data For Account", "History", "Web Data", "Bookmarks", "Cookies",
                   "Local State", "Preferences", "Secure Preferences", "Extensions", "Sessions", "Favicons",
                   "Top Sites", "Shortcuts", "Sync Data", "Affiliation Database", "Network Persistent State",
                   ".env", "Local Storage", "Session Storage", "Cache", "Code Cache", "GPUCache"}
FORBIDDEN_SUFFIXES = (".har", ".log", ".sqlite-wal", ".sqlite-shm")


# --------------------------------------------------------------------------------------------- pure helpers
def tiktok_cookies(cookies: list) -> list:
    """Only cookies that belong to TikTok's own domains."""
    return [c for c in cookies if "tiktok" in str(c.get("domain", "")).lower()]


def cookie_param(c: dict, now: float | None = None) -> dict:
    """A cookie as exported by Storage.getCookies -> the CookieParam Storage.setCookies accepts. Session cookies
    (no expiry) are given 30 days so they survive the importing browser being closed."""
    now = now or time.time()
    exp = c.get("expires", -1)
    param = {"name": c["name"], "value": c["value"], "domain": c["domain"], "path": c.get("path") or "/",
             "secure": bool(c.get("secure")), "httpOnly": bool(c.get("httpOnly")),
             "expires": exp if (exp and exp > now) else now + 30 * 86400}
    if c.get("sameSite") in ("Strict", "Lax", "None"):
        param["sameSite"] = c["sameSite"]
    if c.get("priority") in ("Low", "Medium", "High"):
        param["priority"] = c["priority"]
    return param


def env_template(env: dict, example_text: str = "") -> str:
    """A .env for the server: non-secret settings carried over, every secret left blank to be filled in there."""
    lines = ["# Generated by `python run.py package`. Fill in the blank secrets; paths are for the SERVER.", ""]
    keep_keys = ("TARGET_PROFILE_URL", "TARGET_VIDEO_URL", "BRAND_NAME", "POSTING_ENABLED", "POLL_INTERVAL_SECONDS",
                 "TELEGRAM_CHAT_ID", "BFP_PROFILE_NAME", "BFP_HEADLESS", "BFP_BACKEND")
    for key in ("OPENROUTER_API_KEY", "TELEGRAM_BOT_TOKEN"):
        lines.append(f"{key}=            # secret: fill in on the server")
    for key in keep_keys:
        if key in env:
            value = env[key]
            if any(w in key.upper() for w in SECRET_NAMES):
                value = ""
            lines.append(f"{key}={value}")
    lines += ["", "# the server's browser binary (Brave recommended; it only needs to exist, nothing is downloaded):",
              "BFP_BACKEND=patched", "BFP_HEADLESS=true", "BFP_PATCHED_CHROMIUM=      # e.g. /usr/bin/brave-browser or C:\\Program Files\\...\\brave.exe",
              "# filled in automatically by `python run.py restore-profiles` (it prints the line to paste):",
              "BFP_USER_DATA_DIR=", ""]
    return "\n".join(lines)


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def build_manifest(root: Path) -> dict:
    files = {}
    for p in sorted(root.rglob("*")):
        if p.is_file() and p.name != "MANIFEST.json":
            files[p.relative_to(root).as_posix()] = {"bytes": p.stat().st_size, "sha256": sha256_of(p)}
    return {"created": time.strftime("%Y-%m-%d %H:%M:%S"), "files": files}


def verify_bundle(root: Path) -> list:
    """Problems that would leak something that must not travel. [] = clean."""
    root = Path(root)
    problems = []
    for p in root.rglob("*"):
        rel = p.relative_to(root)
        parts = rel.parts
        in_profiles = parts and parts[0] == "profiles"
        if p.is_file():
            inside_idb = in_profiles and len(parts) >= 4 and parts[2] == "indexeddb"      # LevelDB has its own *.log files
            if p.name in FORBIDDEN_NAMES or (p.name.endswith(FORBIDDEN_SUFFIXES) and not inside_idb):
                problems.append(f"forbidden file: {rel}")
            if in_profiles:
                ok = (len(parts) == 3 and parts[2] == "state.json") or \
                     (len(parts) >= 4 and parts[2] == "indexeddb" and "tiktok" in parts[3].lower())
                if not ok:
                    problems.append(f"not TikTok-only state inside a profile: {rel}")
            if p.name == ".env" or (p.name.startswith(".env") and p.name not in (".env.example", ".env.template")):
                problems.append(f"secrets file: {rel}")
        elif p.is_dir() and p.name in FORBIDDEN_NAMES and p.name not in ("tests",):
            problems.append(f"forbidden folder: {rel}")
    return problems


def snapshot_db(src: Path, dst: Path) -> None:
    """Consistent copy of the live database (sqlite backup API), with runtime-only state removed."""
    dst.parent.mkdir(parents=True, exist_ok=True)
    source = sqlite3.connect(str(src), timeout=30)
    target = sqlite3.connect(str(dst))
    try:
        source.backup(target)
        target.execute("DELETE FROM chat_state")
        target.execute("DELETE FROM events")
        target.execute("DELETE FROM meta WHERE key IN ('ai_exhausted_day','last_scan_error','budget_alert_day',"
                       "'scan_error_alerted_at','models_checked_day','model_chain','paused')")
        target.commit()
        target.execute("VACUUM")
    finally:
        source.close()
        target.close()


# ---------------------------------------------------------------------------------- browser-driven pieces
def _executable() -> str:
    exe = os.environ.get("BFP_PATCHED_CHROMIUM", "")
    if not exe or not Path(exe).exists():
        raise RuntimeError("BFP_PATCHED_CHROMIUM must point at the browser binary")
    return exe


def _launch(user_data_dir: Path, headless: bool = True):
    saved = os.environ.get("BFP_USER_DATA_DIR")
    os.environ["BFP_USER_DATA_DIR"] = str(user_data_dir)
    try:
        browser = bfp.CDPBrowser(bfp.ProfileFactory().desktop(), executable=_executable(), headless=headless)
    finally:
        if saved is None:
            os.environ.pop("BFP_USER_DATA_DIR", None)
        else:
            os.environ["BFP_USER_DATA_DIR"] = saved
    browser.start()
    return browser


def _browser_call(ws_url: str, method: str, **params) -> dict:
    # generous: an old, shared server can take a long time to answer its first command while a fresh profile is scanned
    ws = bfp.WSClient(ws_url, timeout=90)
    try:
        ws.send(json.dumps({"id": 1, "method": method, "params": params}))
        for _ in range(30):
            frame = json.loads(ws.recv(timeout=90))
            if frame.get("id") == 1:
                if "error" in frame:
                    raise RuntimeError(f"{method}: {frame['error'].get('message')}")
                return frame.get("result") or {}
    finally:
        ws.close()
    return {}


def _idb_dirs(user_data_dir: Path) -> list:
    base = Path(user_data_dir) / "Default" / "IndexedDB"
    return sorted(d for d in base.iterdir() if d.is_dir() and "tiktok" in d.name.lower()) if base.exists() else []


def export_state(name: str, user_data_dir: Path, bundle_profile_dir: Path) -> dict:
    """Read one profile's TikTok state through a short headless launch of it and write it into the bundle."""
    user_data_dir = Path(user_data_dir)
    # the browser launcher itself holds the profile's lock for the browser's whole lifetime
    browser = _launch(user_data_dir)
    try:
        page = browser.driver
        ws_url = page.browser_info["webSocketDebuggerUrl"]
        page.goto("https://www.tiktok.com/")
        time.sleep(4)
        who = json.loads(page.evaluate(acct._WHO_JS) or "{}")
        local_storage = json.loads(page.evaluate(
            "JSON.stringify(Object.fromEntries(Object.entries(localStorage)))") or "{}")
        idb_names = json.loads(page.evaluate(
            "indexedDB.databases().then(d => JSON.stringify(d.map(x => x.name)))", await_promise=True) or "[]")
        user_agent = page.evaluate("navigator.userAgent")
        cookies = tiktok_cookies(acct._cookies(ws_url))
        version = page.browser_info.get("Browser", "")
    finally:
        browser.stop()                      # graceful: LevelDB flushed before the IndexedDB folders are copied
    state = {"name": name, "username": who.get("uniqueId"), "nickname": who.get("nickName"),
             "region": who.get("region"), "exported_at": time.strftime("%Y-%m-%d %H:%M:%S"),
             "browser": version, "user_agent": user_agent, "cookies": cookies, "local_storage": local_storage,
             "idb_databases": idb_names}
    out = Path(bundle_profile_dir)
    out.mkdir(parents=True, exist_ok=True)
    for d in _idb_dirs(user_data_dir):
        shutil.copytree(d, out / "indexeddb" / d.name)
    (out / "state.json").write_text(json.dumps(state, ensure_ascii=False, indent=1), encoding="utf-8")
    return {"name": name, "username": state["username"], "cookies": len(cookies),
            "session_cookie": any(c["name"] in ("sessionid", "sid_tt") for c in cookies),
            "local_storage_keys": len(local_storage), "idb": [d.name for d in _idb_dirs(user_data_dir)]}


def select_accounts(chain: list, only: list | None) -> list:
    """The accounts a bundle should carry: all of the chain, or just the named ones (e.g. one newly added account)."""
    if not only:
        return list(chain)
    wanted = [n.strip() for n in only if n and n.strip()]
    unknown = [n for n in wanted if n not in chain]
    if unknown:
        raise RuntimeError(f"unknown account(s): {', '.join(unknown)} (known: {', '.join(chain)})")
    return [n for n in chain if n in wanted]


def package(out_dir: Path, *, include_sessions: bool = True, include_db: bool = True,
            force: bool = False, progress=print, only_accounts: list | None = None) -> dict:
    out = Path(out_dir)
    if out.exists() and any(out.iterdir()):
        if not force:
            raise RuntimeError(f"{out} is not empty (use --force to replace it)")
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)
    root = config.ROOT

    # 1. code (an explicit allow-list, so nothing else on this machine can sneak in)
    for f in CODE_FILES:
        if (root / f).exists():
            shutil.copy2(root / f, out / f)
    for d in CODE_DIRS:
        if (root / d).is_dir():
            shutil.copytree(root / d, out / d, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "*.log"))
    bfp_py = ensure_bfp_on_path() / "bfp.py"
    (out / "vendor").mkdir(exist_ok=True)
    shutil.copy2(bfp_py, out / "vendor" / "bfp.py")

    # 2. TikTok-only state of the profiles the bot actually uses
    exported = []
    chain = select_accounts(config.account_chain(), only_accounts)
    for name in chain:
        folder = Path(config.account_user_data_dir(name))
        progress(f"exporting TikTok state of {name} ...")
        info = export_state(name, folder, out / "profiles" / name)
        exported.append(info)
        progress(f"  @{info['username']}: {info['cookies']} TikTok cookies, {info['local_storage_keys']} localStorage "
                 f"keys, IndexedDB {info['idb']}")
        if not include_sessions:
            sp = out / "profiles" / name / "state.json"
            st = json.loads(sp.read_text(encoding="utf-8"))
            st["cookies"] = []
            sp.write_text(json.dumps(st, ensure_ascii=False, indent=1), encoding="utf-8")

    # 3. settings / history database, accounts list, env template
    if include_db and config.DB_FILE.exists():
        snapshot_db(config.DB_FILE, out / "data" / "bot.db")
    (out / "data").mkdir(exist_ok=True)
    reg = [{"name": a["name"], "username": a.get("username"), "region": a.get("region"),
            "enabled": a.get("enabled", True)} for a in config.load_accounts()]
    (out / "data" / "accounts.template.json").write_text(
        json.dumps({"master": config.BFP_PROFILE_NAME, "accounts": reg}, indent=1), encoding="utf-8")
    from app.env_loader import load_env
    example = (root / ".env.example").read_text(encoding="utf-8") if (root / ".env.example").exists() else ""
    current = {}
    try:
        current = load_env(root / ".env")
    except Exception:  # noqa: BLE001
        pass
    (out / ".env.template").write_text(env_template(current, example), encoding="utf-8")

    # 4. self-check + manifest
    problems = verify_bundle(out)
    manifest = build_manifest(out)
    manifest["profiles"] = exported
    manifest["sessions_included"] = include_sessions
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    return {"out": str(out), "profiles": exported, "problems": problems, "files": len(manifest["files"]),
            "mb": round(sum(f["bytes"] for f in manifest["files"].values()) / 1048576, 2)}


# --------------------------------------------------------------------------------------- server side
def restore_profile(name: str, bundle_profile_dir: Path, target_user_data_dir: Path, *, keep_secrets: bool = False) -> dict:
    """Rebuild a clean profile folder from the exported TikTok state and prove it is logged in."""
    bundle_profile_dir = Path(bundle_profile_dir)
    target = Path(target_user_data_dir)
    state = json.loads((bundle_profile_dir / "state.json").read_text(encoding="utf-8"))
    (target / "Default" / "IndexedDB").mkdir(parents=True, exist_ok=True)
    copied = []
    for d in (bundle_profile_dir / "indexeddb").glob("*") if (bundle_profile_dir / "indexeddb").exists() else []:
        dest = target / "Default" / "IndexedDB" / d.name
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(d, dest)
        copied.append(d.name)
    browser = _launch(target)
    try:
        page = browser.driver
        ws_url = page.browser_info["webSocketDebuggerUrl"]
        now = time.time()
        cookies = [cookie_param(c, now) for c in state.get("cookies", [])]
        if cookies:
            _browser_call(ws_url, "Storage.setCookies", cookies=cookies)
        page.goto("https://www.tiktok.com/robots.txt")            # a cheap document on TikTok's origin
        items = state.get("local_storage") or {}
        ls_keys = page.evaluate("(function(){const it=%s; for (const k in it) localStorage.setItem(k, it[k]);"
                                " return Object.keys(localStorage).length})()" % json.dumps(items))
        page.goto("https://www.tiktok.com/")
        time.sleep(5)
        who = json.loads(page.evaluate(acct._WHO_JS) or "{}")
        idb_names = json.loads(page.evaluate(
            "indexedDB.databases().then(d => JSON.stringify(d.map(x => x.name)))", await_promise=True) or "[]")
        have = tiktok_cookies(acct._cookies(ws_url))
    finally:
        browser.stop()
    logged_in = any(c["name"] in ("sessionid", "sid_tt") for c in have) and bool(who.get("uniqueId"))
    result = {"name": name, "logged_in": logged_in, "username": who.get("uniqueId"),
              "expected_username": state.get("username"),
              "same_account": bool(who.get("uniqueId")) and who.get("uniqueId") == state.get("username"),
              "cookies_set": len(cookies), "cookies_now": len(have), "local_storage_keys": ls_keys,
              "idb_copied": copied, "idb_databases_expected": state.get("idb_databases"), "idb_databases_now": idb_names}
    if logged_in and not keep_secrets:
        (bundle_profile_dir / "state.json").unlink()                 # the clear-text cookies are not needed any more
    return result


def restore_profiles(bundle_dir: Path, root: Path, *, keep_secrets: bool = False, progress=print) -> dict:
    """Server side: rebuild every profile under <root>/profiles/<name>/User Data and write <root>/data/accounts.json."""
    bundle_dir, root = Path(bundle_dir), Path(root)
    template = json.loads((bundle_dir / "data" / "accounts.template.json").read_text(encoding="utf-8"))
    master = template["master"]
    acc_file = root / "data" / "accounts.json"
    try:                                                  # a re-run after a partial restore must keep what already worked
        previous = json.loads(acc_file.read_text(encoding="utf-8")) if acc_file.exists() else {}
    except (OSError, ValueError):
        previous = {}
    known = {a["name"]: a for a in previous.get("accounts", []) if a.get("name")}
    master_username = previous.get("master_username")
    results = []
    for state_file in sorted((bundle_dir / "profiles").glob("*/state.json")):
        name = state_file.parent.name
        target = root / "profiles" / name / "User Data"
        progress(f"restoring {name} -> {target}")
        res = None
        for attempt in (1, 2, 3):                         # a slow, busy server may need more than one go
            try:
                res = restore_profile(name, state_file.parent, target, keep_secrets=keep_secrets)
                break
            except Exception as exc:  # noqa: BLE001
                progress(f"  attempt {attempt}/3 failed: {type(exc).__name__}: {exc}")
                res = {"name": name, "logged_in": False, "username": None, "expected_username": None, "cookies_set": 0,
                       "cookies_now": 0, "local_storage_keys": 0, "error": f"{type(exc).__name__}: {exc}"}
                time.sleep(10)
            if res.get("logged_in"):
                break
        results.append(res)
        progress(f"  logged_in={res['logged_in']} @{res['username']} (expected @{res['expected_username']}), "
                 f"cookies {res['cookies_set']}->{res['cookies_now']}, localStorage keys {res['local_storage_keys']}")
        if res.get("logged_in") and name == master:
            master_username = res["username"]
        if res.get("logged_in") and name != master:
            meta = next((a for a in template["accounts"] if a["name"] == name), {})
            known[name] = {"name": name, "user_data_dir": str(target), "username": res["username"] or meta.get("username"),
                           "region": meta.get("region"), "enabled": meta.get("enabled", True),
                           "added": time.strftime("%Y-%m-%d %H:%M:%S")}
    # state.json is deleted only once a login was PROVEN, so a profile that exists without one was restored in an earlier run
    for a in template["accounts"]:
        done_before = (root / "profiles" / a["name"] / "User Data" / "Default").exists() \
            and not (bundle_dir / "profiles" / a["name"] / "state.json").exists()
        if a["name"] not in known and done_before:
            known[a["name"]] = {"name": a["name"], "user_data_dir": str(root / "profiles" / a["name"] / "User Data"),
                                "username": a.get("username"), "region": a.get("region"),
                                "enabled": a.get("enabled", True), "added": time.strftime("%Y-%m-%d %H:%M:%S")}
    accounts = [known[a["name"]] for a in template["accounts"] if a["name"] in known]     # template order = try order
    (root / "data").mkdir(parents=True, exist_ok=True)
    acc_file.write_text(json.dumps({"accounts": accounts, "master_username": master_username},
                                   ensure_ascii=False, indent=2), encoding="utf-8")
    if (bundle_dir / "data" / "bot.db").exists() and not (root / "data" / "bot.db").exists():
        shutil.copy2(bundle_dir / "data" / "bot.db", root / "data" / "bot.db")
    master_dir = root / "profiles" / master / "User Data"
    master_ok = bool(master_username) or (( master_dir / "Default").exists()
                                          and not (bundle_dir / "profiles" / master / "state.json").exists())
    missing = [n for n in [a["name"] for a in template["accounts"] if a.get("enabled", True)] if n not in known]
    if not master_ok:
        missing.insert(0, master)
    return {"results": results, "env_line": f"BFP_USER_DATA_DIR={master_dir}", "master": master, "missing": missing,
            "all_logged_in": all(r["logged_in"] for r in results) and not missing}
